// norm reduces a value to a comparable string, so a Go argument and whatever
// SQLite handed back can be compared without caring which of int64/float64/
// []byte the driver chose.
func norm(v any) string {
	switch x := v.(type) {
	case nil:
		return "NULL"
	case bool:
		if x {
			return "1"
		}
		return "0"
	case *int:
		if x == nil {
			return "NULL"
		}
		return strconv.Itoa(*x)
	case *float64:
		if x == nil {
			return "NULL"
		}
		return strconv.FormatFloat(*x, 'g', -1, 64)
	case int:
		return strconv.Itoa(x)
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case []byte:
		return string(x)
	case string:
		return x
	default:
		return "?"
	}
}

